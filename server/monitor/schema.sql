CREATE TABLE IF NOT EXISTS monitor_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL,
    host text NOT NULL,
    port integer NOT NULL CHECK (port IN (143, 993)),
    secure boolean NOT NULL,
    username text NOT NULL,
    auth_mode text NOT NULL CHECK (auth_mode IN ('password', 'google-oauth')),
    secret text NOT NULL,
    folder text NOT NULL,
    poll_seconds integer NOT NULL DEFAULT 60 CHECK (poll_seconds BETWEEN 30 AND 3600),
    enabled boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    revision integer NOT NULL DEFAULT 0,
    mailbox_epoch integer NOT NULL DEFAULT 0,
    status text NOT NULL DEFAULT 'stopped' CHECK (status IN ('stopped','connecting','active','reconnecting','error')),
    uid_validity bigint,
    last_uid bigint NOT NULL DEFAULT 0,
    last_check_at timestamptz,
    last_message_at timestamptz,
    next_check_at timestamptz,
    check_requested_at timestamptz,
    check_handled_at timestamptz,
    lease_owner uuid,
    lease_until timestamptz
);

