CREATE UNIQUE INDEX IF NOT EXISTS monitor_accounts_inbox_idx
    ON monitor_accounts (lower(email), folder) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS monitor_accounts_login_idx
    ON monitor_accounts (host, lower(username), folder) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS monitor_emails (
    account_id bigint NOT NULL REFERENCES monitor_accounts(id),
    mailbox_epoch integer NOT NULL,
    uid_validity bigint NOT NULL,
    uid bigint NOT NULL,
    message_id_hash text,
    received_at timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN ('done','ignored','error')),
    PRIMARY KEY (account_id, mailbox_epoch, uid_validity, uid),
    UNIQUE (account_id, message_id_hash)
);

CREATE TABLE IF NOT EXISTS monitor_listings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL DEFAULT 'avito',
    external_id text,
    url text,
    photo_url text,
    title text,
    description text,
    price numeric(16,2) CHECK (price >= 0),
    previous_price numeric(16,2),
    category text,
    deal text,
    city text,
    district text,
    address text,
    area numeric(12,2) CHECK (area > 0),
    rooms integer CHECK (rooms >= 0),
    seller_type text,
    seller_name text,
    published_at timestamptz,
    first_received_at timestamptz NOT NULL,
    last_received_at timestamptz NOT NULL,
    details_received_at timestamptz NOT NULL,
    is_new boolean NOT NULL DEFAULT true,
    favorite boolean NOT NULL DEFAULT false,
    archived boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    CHECK (external_id IS NOT NULL OR url IS NOT NULL),
    UNIQUE (source, external_id),
    UNIQUE (source, url)
);

CREATE INDEX IF NOT EXISTS monitor_listings_inbox_idx
    ON monitor_listings (is_new DESC, last_received_at DESC, id DESC) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS monitor_listing_sources (
    listing_id bigint NOT NULL REFERENCES monitor_listings(id),
    account_id bigint NOT NULL REFERENCES monitor_accounts(id),
    search_name text NOT NULL DEFAULT '',
    last_received_at timestamptz NOT NULL,
    PRIMARY KEY (listing_id, account_id, search_name)
);
CREATE INDEX IF NOT EXISTS monitor_listing_sources_account_idx
    ON monitor_listing_sources (account_id, search_name, listing_id);
CREATE INDEX IF NOT EXISTS monitor_listing_sources_recent_idx
    ON monitor_listing_sources (last_received_at DESC);

CREATE TABLE IF NOT EXISTS monitor_price_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id bigint NOT NULL REFERENCES monitor_listings(id),
    old_price numeric(16,2) NOT NULL,
    new_price numeric(16,2) NOT NULL,
    changed_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS monitor_price_history_listing_idx ON monitor_price_history (listing_id, id DESC);

CREATE TABLE IF NOT EXISTS monitor_task_details (
    task_id bigint PRIMARY KEY REFERENCES tasks(id),
    listing_id bigint NOT NULL UNIQUE REFERENCES monitor_listings(id),
    url text,
    description text,
    price numeric(16,2) CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS monitor_settings (
    user_id bigint PRIMARY KEY REFERENCES users(id),
    toast boolean NOT NULL DEFAULT true,
    sound boolean NOT NULL DEFAULT false,
    desktop boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS monitor_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint REFERENCES monitor_accounts(id),
    actor_id bigint REFERENCES users(id),
    level text NOT NULL CHECK (level IN ('info','error')),
    code text NOT NULL,
    uid bigint,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS monitor_logs_recent_idx ON monitor_logs (created_at DESC, id DESC);
