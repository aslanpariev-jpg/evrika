CREATE TABLE IF NOT EXISTS users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL, login text NOT NULL UNIQUE, password_hash text NOT NULL,
 role text NOT NULL CHECK(role IN ('admin','employee')), active boolean NOT NULL DEFAULT true,
 token_version integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS clients (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, phone text NOT NULL, address text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS tasks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id bigint NOT NULL REFERENCES clients(id),
 direction text NOT NULL CONSTRAINT tasks_direction_monitor_check CHECK(direction IN ('selection','sale','rent')),
 deal text NOT NULL CONSTRAINT tasks_deal_monitor_check CHECK(deal IN ('buy','sell','rent')),
 property_type text CHECK(property_type IN ('house','apartment','land','commercial','other')),
 scope text NOT NULL CHECK(scope IN ('common','personal')), owner_id bigint REFERENCES users(id),
 result text NOT NULL DEFAULT 'none' CHECK(result IN ('none','success','failed','postponed')),
 result_date date, is_new boolean NOT NULL DEFAULT true, deleted_at timestamptz,
 revision integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK((result='none' AND result_date IS NULL) OR (result<>'none' AND result_date IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS comments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id bigint NOT NULL REFERENCES tasks(id),
 author_id bigint NOT NULL REFERENCES users(id), author_name text NOT NULL,
 kind text NOT NULL CHECK(kind IN ('working','done')), body text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id bigint REFERENCES users(id), actor_name text NOT NULL,
 action text NOT NULL, task_id bigint REFERENCES tasks(id), details jsonb NOT NULL DEFAULT '{}'::jsonb, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tasks_owner_idx ON tasks(owner_id);
CREATE INDEX IF NOT EXISTS tasks_order_idx ON tasks(is_new DESC,created_at DESC);
CREATE INDEX IF NOT EXISTS comments_task_idx ON comments(task_id,id);
CREATE INDEX IF NOT EXISTS audit_date_idx ON audit(created_at DESC);
